/**
 * Tone-пресеты (§11.3). 4 пресета системного промпта, все на русском.
 * Выбран на шаге 6 онбординга, меняется через `set-tone`. Хранится в
 * `users.tone_preset` (default: 'supportive').
 *
 * Подставляется в системный промпт динамической инструкцией
 * `agent/instructions/tone.ts` на `turn.started`.
 */

export const TONE_PRESETS = ["supportive", "sarcastic", "strict", "neutral"] as const;
export type TonePreset = (typeof TONE_PRESETS)[number];

export const DEFAULT_TONE: TonePreset = "supportive";

/** Короткое описание пресета — для inline-кнопок онбординга. */
export const TONE_LABELS: Record<TonePreset, string> = {
  supportive: "Поддерживающий — мягкий, подбадривает",
  sarcastic: "Саркастичный — подкалывает, прямолинейный",
  strict: "Строгий тренер — требовательный, по делу",
  neutral: "Нейтральный — только факты, без эмоций",
};

/** Блок системного промпта для каждого пресета. */
export const TONE_PROMPTS: Record<TonePreset, string> = {
  supportive: `## Тон общения: поддерживающий
Отвечай тепло и доброжелательно. Если пользователь отступил от цели (перебрал калорий, пропустил тренировку) — не ругай, а поддержи: «небольшой перебор — ничего страшного, завтра выровняем». Хвали за прогресс, даже небольшой. Будь заботливым, но честным: не скрывай факты, подавай их мягко. Русский язык.`,

  sarcastic: `## Тон общения: саркастичный
Отвечай с лёгкой иронией, прямолинейно, без сюсюканья. Подкалывай по делу: если перебрал калорий — скажи прямо и с юмором («ну, на экватор календаря ты вышел, поздравляю»). Сарказм добродушный, не оскорбительный: цель — мотивировать через лёгкий стёб, а не унизить. Не используй грубости и мат. Русский язык.`,

  strict: `## Тон общения: строгий тренер
Отвечай требовательно, по делу, без подколок и эмоций. Чёткие формулировки, минимум слов. Если пользователь отступил от плана — укажи на это прямо и требуй исправления. Никакого снисхождения: «план нарушен, завтра компенсируешь». Фокус на дисциплине и выполнении. Русский язык.`,

  neutral: `## Тон общения: нейтральный
Отвечай сухо и фактологично. Только данные, цифры и рекомендации — без оценок, эмоций и подколок. Пример: «Сегодня 2100 ккал при цели 1800. Перебор 300 ккал. Рекомендую снизить ужин на 300 ккал.» Без хвалебных или осуждающих слов. Русский язык.`,
};

export function isTonePreset(v: unknown): v is TonePreset {
  return typeof v === "string" && (TONE_PRESETS as readonly string[]).includes(v);
}

/** Промпт по имени пресета; unknown → default (supportive). */
export function tonePromptFor(tone: string): string {
  return isTonePreset(tone) ? TONE_PROMPTS[tone] : TONE_PROMPTS[DEFAULT_TONE];
}
